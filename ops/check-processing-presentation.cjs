const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const ui = fs.readFileSync(path.join(root, 'administration/src/components/Processamento/ProcessamentoDetalhesPage.tsx'), 'utf8');
const eventSource = ui.match(/function historicalEvent\([^]*?\n\}/)[0].replace('formula: ResultDetail["formulaUtilizada"] | undefined', 'formula');
const event = Function(eventSource + ';return historicalEvent')();
assert.equal(event({codEvento:'0042',versao:2}), 'Evento RM: 0042');
assert.equal(event({codEvento:null}), 'Sem evento RM vinculado');
assert.equal(event(null), 'Evento RM histórico indisponível');
assert.equal(event({codEvento:'9999',snapshot_origem:'CONFERENCIA_LEGADO'}), 'Evento RM histórico indisponível');
const processSource = ui.slice(ui.indexOf('  const process ='), ui.indexOf('  const refresh =')).replace('etapa: Etapa, baseIds?: number[], repeat = false', 'etapa, baseIds, repeat = false');
const calls = [];
const run = Function('command', 'id', processSource + 'return process;')({run: request => calls.push(request)}, 42);
run('VARIAVEIS'); run('VALORES', [7]); run('VARIAVEIS', [7], true); run('ENVIAR_RM', [7], true);
assert.deepEqual(calls[0], {etapa:'VARIAVEIS',execucaoIds:[42],recalcular:false});
assert.deepEqual(calls[1], {etapa:'VALORES',execucaoIds:[42],baseIds:[7],recalcular:false});
assert.equal(calls[2].recalcular,true);
assert.equal(calls[3].recalcular,false);
assert.ok(!ui.includes('<nav className="op-tabs"'));
assert.ok(ui.includes('process("VARIAVEIS", undefined, recalculate)'));
assert.ok(ui.includes('process("VALORES", [b.execucao_funcionario_base_id])'));
const api = fs.readFileSync(path.join(root, 'api/src/execucao/operacao.service.ts'), 'utf8');
const mapping = api.slice(api.indexOf('bases: bases.map('),api.indexOf('      queue,',api.indexOf('bases: bases.map('))).replace(/^bases: /,'').trim().replace(/,$/,'').replace(/let formulaUtilizada: \{[^]*?\} \| null = null;/,'let formulaUtilizada = null;');
const bases=[{execucao_funcionario:[{formula:{codEvento:'9999'},formula_snapshot:JSON.stringify({codEvento:'0042',versao:2})},{formula:{codEvento:'9999'},formula_snapshot:null},{formula:{codEvento:'9999'},formula_snapshot:'invalid'}]}];
const mapped=Function('bases','return '+mapping)(bases)[0].execucao_funcionario;
assert.equal(mapped[0].formulaUtilizada.codEvento,'0042');
assert.equal(mapped[0].formulaUtilizada.versao,2);
assert.equal(mapped[1].formulaUtilizada,null);
assert.equal(mapped[2].formulaUtilizada,null);
assert.ok(!('formula_snapshot' in mapped[0]));
console.log('PASS: snapshot overrides current event; missing/invalid legacy snapshot; branch/person scope; explicit recalculation; single view');
